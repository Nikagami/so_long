int	check_path(char **map)
{
	int	x;
	int	y;

	x = 1;
	while (map[x])
	{
		y = 1;
		while (map[x][y])
		{
			if (map[x][y] == 'C' || map[x][y] == 'E')
				return (0);
			y++;
		}
		x++;
	}
	return (1);
}
